const example = (body: string): GuideSection => ({
  role: "example",
  heading: "Например",
  body,
});
const detail = (heading: string, body: string): GuideSection => ({
  role: "detail",
  heading,
  body,
});
const distinction = (heading: string, body: string): GuideSection => ({
  role: "distinction",
  heading,
  body,
});
const steps = (heading: string, ...items: string[]): GuideSection => ({
  role: "steps",
  heading,
  items,
});
