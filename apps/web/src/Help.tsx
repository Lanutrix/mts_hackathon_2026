import { platformIcons, iconNames } from "../../../packages/domain/platformIcons";
import { useEffect, type ReactNode } from "react";
import { guidePages } from "../../../packages/domain/assistantGuide";
import AccessIcon, { accessLabels } from "./AccessIcon";
import { Icon, iconLabels, type IconName } from "./Brand";
import { screenLink } from "./routes";
import "./help.css";

const sections = [
  ["incident", "Что такое инцидент"],
  ["shift", "Эфир и симптомы"],
  ["assistant", "ИИ-помощник"],
  ["ticket", "Карточка и назначение"],
  ["signals", "Уведомления"],
  ["monitor", "Общий экран"],
  ["devices", "Устройство и доступ"],
  ["icons", "Словарь иконок"],
] as const;
export default function Help({
  ns,
  go,
}: {
  ns: string;
  go: (path: string) => void;
}) {
  useEffect(() => {
    const scrollToTopic = () => {
      const id = location.hash.slice(1);
      if (sections.some(([key]) => key === id))
        document.getElementById(id)?.scrollIntoView();
    };
    scrollToTopic();
    window.addEventListener("hashchange", scrollToTopic);
    return () => window.removeEventListener("hashchange", scrollToTopic);
  }, []);
  function jump(path: string, label: string) {
    const href = path === "/preferences" ? path : screenLink(path, ns);
    return (
      <a
        href={href}
        onClick={(e) => {
          if (e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
          e.preventDefault();
          go(href);
        }}
      >
        {label} ↗
      </a>
    );
  }
  function topic(
    id: (typeof sections)[number][0],
    icon: IconName,
    children: ReactNode,
  ) {
    return (
      <section id={id} className="help-topic">
        <h2>
          <Icon name={icon} />
          {sections.find((s) => s[0] === id)![1]}
        </h2>
        {children}
      </section>
    );
  }
  return (
    <section className="srez-help">
      <h1>Помощь</h1>
      <div className="help-grid">
        <nav aria-label="Содержание помощи">
          {sections.map(([id, title]) => (
            <a key={id} href={"#" + id}>
              {title}
            </a>
          ))}
        </nav>
        <div>
          {topic(
            "incident",
            "research",
            <>
              <p>{guidePages.incident.lead}</p>
              <p>{guidePages.incident.sections[0].body}</p>
              <p>{guidePages.incident.sections[1].body}</p>
              <p>{guidePages.massIncident.lead}</p>
              <p>{guidePages.problem.lead}</p>
              <p>В исходном наборе демо 800 синтетических заявок. У 26 профильных команд есть свои услуги и исполнители. Например, биллинг разбирает повторное начисление, а команда видеоплеера — остановку архивной передачи после заставки.</p>
              {jump("/live", "Посмотреть заявки")}
            </>,
          )}
          {topic(
            "shift",
            "live",
            <>
              <p>
                Три числа относятся к текущей выборке. Первое считает уникальные
                заявки в наблюдаемых группах, второе — заявки с прошедшим
                сроком, третье — инциденты, где потребуется устранение последствий. Одна заявка
                может входить в оба последних числа.
              </p>
              <p>
                Эфир сначала показывает критические заявки у срока, затем остальные критические,
                  просроченные и близкие к сроку. Граница близкого срока — 15 минут.
                  Внутри очереди раньше идёт ближайший срок, затем приоритет и номер заявки.
                  Откройте группу и выберите «По симптомам и продуктам», чтобы найти повторения
                  внутри неё. В подробностях можно подготовить сводку для передачи.
                </p>
                <p>
                  Симптом объединяет похожие проявления. Например, «тайм-аут» и
                «рост времени ответа» попадут в одну группу. Для проверки
                откройте пример и прочитайте исходный текст. Если важнее
                ответственность, переключите группировку на команды.
              </p>
              <p>
                В «Следующем шаге» видно, что проверить и по какому инциденту.
                Совет обновляется при изменении группы, статуса или срока. Кнопка
                «Подробнее» открывает поля, на которых он основан.
              </p>
              {jump("/live", "Открыть эфир")}
            </>,
          )}
          {topic(
            "assistant",
            "layers",
            <>
              <p>
                Введите вопрос внизу холста. Попробуйте «Сгруппируй по командам
                и рядом покажи сроки», затем «А теперь только просроченные».
                Можно начать и со справочного вопроса, например «Что такое
                инцидент?». Нажмите на группу, чтобы увидеть её обращения и
                открыть карточку.
              </p>
              <p>
                ИИ выбирает представление, а числа рассчитываются по снимку
                источника. При недоступности модели поддерживаемые запросы
                выполняются по полям ITSM. История диалога сохраняется при
                возврате из карточки в той же вкладке и очищается при полной
                перезагрузке.
              </p>
              <p>
                В учебном эфире можно попросить «Объясни этот срез простыми словами»,
                продолжить диалог или сменить тему. Во время подготовки ответа его можно остановить
                и отредактировать вопрос.
              </p>
              <p>
                Площадь квадрата по умолчанию соответствует числу заявок в
                группе. Диагональный срез показывает долю просроченных, а
                верхняя риска — долю инцидентов с отметкой об устранении последствий. Можно попросить
                изменить размер квадратов по числу инцидентов с последствиями или сравнить группы
                по приоритету.
              </p>
              {jump("/workspace", "Открыть помощника")}
            </>,
          )}
          {topic(
            "ticket",
            "coordinators",
            <>
              <p>
                В карточке собраны статус, срок, описание и история конкретной
                заявки. ИИ-разбор показывает основания рекомендации. Перейдите
                по ссылке на поле, чтобы сверить её с источником.
              </p>
              <p>
                Координатор может запросить варианты команд и черновик комментария, сверить основания и сохранить свой выбор в журнале. Команда определяет исполнителя. Назначение в ITSM подтверждает человек. Исходные поля можно развернуть и скопировать в разделе JSON.
              </p>
            </>,
          )}
          {topic(
            "signals",
            "bell",
            <>
              <p>
                Полоса сигнала сообщает, когда критическая заявка появилась,
                вернулась в работу, завершилась или оказалась у координаторов.
                Через неё можно открыть инцидент. Скрытие полосы действует в вашей
                вкладке.
              </p>
              <p>
                Журнал хранит события и состояние заявки на момент сигнала. Для
                доставки на устройство разрешите уведомления в настройках и
                воспользуйтесь проверочной отправкой.
              </p>
              {jump("/notifications", "Открыть журнал")}
            </>,
          )}
          {topic(
            "monitor",
            "expand",
            <>
              <p>
                Общий экран предназначен для телевизора или второго монитора. Он
                сам получает обновления и перелистывает заявки. Часы показывают
                секунды в часовом поясе из личных настроек. Там же, в разделе
                «Общий экран», можно выбрать порядок заявок и интервал смены страниц. Чтобы выйти,
                используйте «Назад» в браузере.
              </p>
              {jump("/wallboard", "Открыть общий экран")}
            </>,
          )}
          {topic(
            "devices",
            "settings",
            <>
              <p>
                Выберите светлую, тёмную или системную тему. Выбор хранится в
                браузере этого устройства. Наведите курсор на значок, перейдите
                к кнопке клавишей Tab или удержите её пальцем, чтобы прочитать
                подсказку.
              </p>
              <p>
                Установите приложение через меню браузера, если устройство
                поддерживает установку. В учебном эфире события моделируются,
                данные рабочего источника доступны после входа. Права профиля
                определяют доступные действия.
              </p>
              <p>
                В «Истории» ищите завершённые заявки. «Качество данных»
                показывает записи с противоречиями и пропусками. Администратор
                может проверить импорт и управлять демонстрацией отдельно от
                рабочего источника.
              </p>
              {jump("/preferences", "Настройки устройства")}
            </>,
          )}
          {topic(
            "icons",
            "help",
            <dl className="help-icons">
              {iconNames.map(
                icon => (
                  <div key={icon}>
                    <dt>
                      <Icon name={icon} />
                      {iconLabels[icon]}
                    </dt>
                    <dd>{platformIcons[icon].meaning}</dd>
                  </div>
                ),
              )}
              <div>
                <dt>
                  <AccessIcon name="enter" />
                  {accessLabels.enter}
                </dt>
                <dd>Открывает вход в рабочее пространство.</dd>
              </div>
              <div>
                <dt>
                  <AccessIcon name="show" />
                  {accessLabels.show}
                </dt>
                <dd>
                  Позволяет проверить введённые символы. Повторное нажатие
                  скрывает их.
                </dd>
              </div>
              <div>
                <dt>
                  <span aria-hidden="true">← →</span>Страницы выборки
                </dt>
                <dd>
                  Показывают соседние заявки или группы внутри текущего среза.
                </dd>
              </div>
              <div>
                <dt>
                  <span aria-hidden="true">↑</span>Отправить вопрос
                </dt>
                <dd>
                  Строит новое представление. Пока идёт запрос, квадрат на этой
                  кнопке останавливает его.
                </dd>
              </div>
            </dl>,
          )}
        </div>
      </div>
    </section>
  );
}
