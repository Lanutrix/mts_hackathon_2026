import type { ReactNode } from "react";
import AccessIcon, { accessLabels } from "./AccessIcon";
import { Icon, iconLabels, type IconName } from "./Brand";
import { screenLink } from "./routes";
import "./help.css";

const sections = [
  ["shift", "Эфир и симптомы"],
  ["assistant", "ИИ-помощник"],
  ["ticket", "Карточка и назначение"],
  ["signals", "Уведомления"],
  ["monitor", "Общий экран"],
  ["devices", "Устройство и доступ"],
  ["icons", "Словарь иконок"],
] as const;
const meanings: Record<IconName, string> = {
  queue: "Показывает список заявок.",
  live: "Открывает текущую смену и реестр.",
  layers: "Открывает диалог с помощником.",
  critical: "У обращения критический приоритет.",
  high: "У обращения высокий приоритет.",
  research: "Команда исследует ситуацию.",
  coordinators: "Заявка передана координаторам.",
  clock: "Показывает срок решения.",
  escalation: "В источнике отмечена необходимость эскалации.",
  bell: "Открывает журнал сигналов.",
  expand: "Открывает экран для наблюдения на расстоянии.",
  more: "Открывает разделы платформы.",
  quality: "Показывает конфликты и пропуски в источнике.",
  history: "Открывает завершённые обращения.",
  profile: "Открывает меню учётной записи.",
  settings: "Открывает личные настройки.",
  system: "Следует теме устройства.",
  moon: "Включает тёмное оформление.",
  sun: "Включает светлое оформление.",
  help: "Открывает эту справку.",
};
export default function Help({
  ns,
  go,
}: {
  ns: string;
  go: (path: string) => void;
}) {
  function jump(path: string, label: string) {
    const href = path === "/preferences" ? path : screenLink(path, ns);
    return (
      <a
        href={href}
        onClick={(e) => {
          if (e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
          e.preventDefault();
          go(href);
        }}
      >
        {label} ↗
      </a>
    );
  }
  function topic(
    id: (typeof sections)[number][0],
    icon: IconName,
    children: ReactNode,
  ) {
    return (
      <section id={id} className="help-topic">
        <h2>
          <Icon name={icon} />
          {sections.find((s) => s[0] === id)![1]}
        </h2>
        {children}
      </section>
    );
  }
  return (
    <section className="srez-help">
      <h1>Помощь</h1>
      <div className="help-grid">
        <nav aria-label="Содержание помощи">
          {sections.map(([id, title]) => (
            <a key={id} href={"#" + id}>
              {title}
            </a>
          ))}
        </nav>
        <div>
          {topic(
            "shift",
            "live",
            <>
              <p>
                Три числа относятся к текущей выборке. Первое считает уникальные
                заявки в наблюдаемых группах, второе — заявки с прошедшим
                сроком, третье — заявки с отметкой об эскалации. Одна заявка
                может входить в оба последних числа.
              </p>
              <p>
                Симптом объединяет похожие проявления. Например, «тайм-аут» и
                «рост времени ответа» попадут в одну группу. Для проверки
                откройте пример и прочитайте исходный текст. Если важнее
                ответственность, переключите группировку на команды.
              </p>
              <p>
                В «Рисках кейса» высота трёх столбцов показывает, сколько заявок
                просрочено, у скольких срок наступит в ближайшие 15 минут и
                сколько требуют эскалации. Рядом указаны точные значения. Ссылка
                «Пример» ведёт в исходную заявку.
              </p>
              {jump("/live", "Открыть эфир")}
            </>,
          )}
          {topic(
            "assistant",
            "layers",
            <>
              <p>
                Введите вопрос внизу холста. Попробуйте «Сгруппируй по командам
                и рядом покажи сроки», затем «А теперь только просроченные».
                Нажмите на группу, чтобы увидеть её обращения и открыть
                карточку.
              </p>
              <p>
                ИИ выбирает представление, а числа рассчитываются по снимку
                источника. При недоступности модели поддерживаемые запросы
                выполняются по полям ITSM. История диалога сохраняется при
                возврате из тикета в той же вкладке и очищается при полной
                перезагрузке.
              </p>
              <p>
                Площадь квадрата по умолчанию соответствует числу заявок в
                группе. Диагональный срез показывает долю просроченных, а
                верхняя риска — долю заявок к эскалации. Можно попросить
                изменить размер квадратов по числу эскалаций или сравнить группы
                по приоритету.
              </p>
              {jump("/workspace", "Открыть помощника")}
            </>,
          )}
          {topic(
            "ticket",
            "coordinators",
            <>
              <p>
                В карточке собраны статус, срок, описание и история конкретной
                заявки. ИИ-разбор показывает основания рекомендации. Перейдите
                по ссылке на поле, чтобы сверить её с источником.
              </p>
              <p>
                Координатор может выбрать команду и сотрудника, проверить
                нагрузку и сохранить решение о маршрутизации. Решение появится в
                журнале координатора. Назначение в ITSM выполняется вручную.
              </p>
            </>,
          )}
          {topic(
            "signals",
            "bell",
            <>
              <p>
                Полоса сигнала сообщает, когда критическая заявка появилась,
                вернулась в работу, завершилась или оказалась у координаторов.
                Через неё можно открыть тикет. Скрытие полосы действует в вашей
                вкладке.
              </p>
              <p>
                Журнал хранит события и состояние заявки на момент сигнала. Для
                доставки на устройство разрешите уведомления в настройках и
                воспользуйтесь проверочной отправкой.
              </p>
              {jump("/notifications", "Открыть журнал")}
            </>,
          )}
          {topic(
            "monitor",
            "expand",
            <>
              <p>
                Общий экран предназначен для телевизора или второго монитора. Он
                сам получает обновления и перелистывает заявки. Часы показывают
                секунды в часовом поясе из личных настроек. Чтобы выйти,
                используйте «Назад» в браузере.
              </p>
              {jump("/wallboard", "Открыть общий экран")}
            </>,
          )}
          {topic(
            "devices",
            "settings",
            <>
              <p>
                Выберите светлую, тёмную или системную тему. Выбор хранится в
                браузере этого устройства. Наведите курсор на значок, перейдите
                к кнопке клавишей Tab или удержите её пальцем, чтобы прочитать
                подсказку.
              </p>
              <p>
                Установите приложение через меню браузера, если устройство
                поддерживает установку. В учебном эфире события моделируются,
                данные рабочего источника доступны после входа. Права профиля
                определяют доступные действия.
              </p>
              <p>
                В «Истории» ищите завершённые заявки. «Качество данных»
                показывает записи с противоречиями и пропусками. Администратор
                может проверить импорт и управлять демонстрацией отдельно от
                рабочего источника.
              </p>
              {jump("/preferences", "Настройки устройства")}
            </>,
          )}
          {topic(
            "icons",
            "help",
            <dl className="help-icons">
              {(Object.entries(meanings) as [IconName, string][]).map(
                ([icon, detail]) => (
                  <div key={icon}>
                    <dt>
                      <Icon name={icon} />
                      {iconLabels[icon]}
                    </dt>
                    <dd>{detail}</dd>
                  </div>
                ),
              )}
              <div>
                <dt>
                  <AccessIcon name="enter" />
                  {accessLabels.enter}
                </dt>
                <dd>Открывает вход в рабочее пространство.</dd>
              </div>
              <div>
                <dt>
                  <AccessIcon name="show" />
                  {accessLabels.show}
                </dt>
                <dd>
                  Позволяет проверить введённые символы. Повторное нажатие
                  скрывает их.
                </dd>
              </div>
              <div>
                <dt>
                  <span aria-hidden="true">← →</span>Страницы выборки
                </dt>
                <dd>
                  Показывают соседние заявки или группы внутри текущего среза.
                </dd>
              </div>
              <div>
                <dt>
                  <span aria-hidden="true">↑</span>Отправить вопрос
                </dt>
                <dd>
                  Строит новое представление. Пока идёт запрос, квадрат на этой
                  кнопке останавливает его.
                </dd>
              </div>
            </dl>,
          )}
        </div>
      </div>
    </section>
  );
}
